#!/usr/bin/env python3
"""RQT-145: exact integer coboundary witness composition for six cocycles.
Uses the verified RQT-133 and RQT-143 full integer matrices.
"""
from pathlib import Path
import json
import sympy as s
p=Path(__file__).resolve().parent
root=p.parent
read=lambda q:s.sympify(q.read_text(),locals={"Matrix":s.Matrix})
X=read(root/"rqt133"/"X-22x22.txt")
U=read(root/"rqt143"/"order-four-generators-22x6.txt")
I=s.eye(22)
N=I+X+X**2+X**3
assert X**4==I and U.shape==(22,6) and N*U==s.zeros(22,6)
def S(k,u):
    return sum((X**j*u for j in range(k)),s.zeros(22,1))
pairs=wraps=triples=0
rows=[]
for col in range(6):
    u=U[:,col]
    assert S(4,u)==s.zeros(22,1)
    for a in range(4):
        for b in range(4):
            lhs=S((a+b)%4,u)
            rhs=S(a,u)+X**a*S(b,u)
            assert lhs==rhs==S(a,u)+S(b,X**a*u)
            assert X**((a+b)%4)*u-u==(X-I)*lhs
            pairs+=1
            wraps+=int(a+b>=4)
            rows.append((col,a,b,a+b>=4))
            for c in range(4):
                assert (S(a,u)+X**a*S(b,u)+X**(a+b)*S(c,u)
                        == S((a+b+c)%4,u))
                triples+=1
assert (pairs,wraps,triples)==(96,36,384)
result={"RQT":145,"pair_tests":pairs,"wrapped_pair_tests":wraps,
        "triple_tests":triples,"nonzero_residuals":0,
        "four_tick_norm_on_six_generators":"zero",
        "composition":"S_(a+b)=S_a+X^a*S_b",
        "linear_extension":"all 4096 classes generated by six cocycles",
        "scope":"conditional Fermat K3 marking; general Hodge OPEN"}
(p/"results.json").write_text(json.dumps(result,indent=2))
(p/"composition-table.txt").write_text("\n".join(
    f"g{j}: {a}+{b} (mod 4) exact; wrap={wrap}" for j,a,b,wrap in rows))
print(json.dumps(result,indent=2))
